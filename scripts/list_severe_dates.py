"""C3 (v1.1): list TEST-period hours where severe delays really happened, with what the tool said.

Writes reports/severe_delay_dates.md. Use it to pick dates to type into the dashboard.
Run AFTER `python run_all.py` (needs data/processed and models/):
    python scripts/list_severe_dates.py
Honest by construction: every row shows the real outcome AND the forecast made 6 h earlier
(RED / AMBER / GREEN), so misses are listed too, not only hits.
"""
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from backend.api import predict          # noqa: E402
from backend.common import config, path  # noqa: E402

LEAD = 6


def main(top: int = 12):
    f = pd.read_parquet(path("processed_dir") / "flights_clean.parquet")
    hubs = list(config()["airports"])
    f = f[f["airport_dep"].isin(hubs) & (f["split_dep"] == "test")].copy()
    f["T"] = pd.to_datetime(f["sched_dep_utc"], utc=True).dt.floor("h")
    g = (f.groupby(["airport_dep", "T"])
          .agg(n=("severe", "size"), n_severe=("severe", "sum"), max_delay=("dep_delay_min", "max"),
               cancelled=("cancelled", "sum")).reset_index())
    g = g[g["n_severe"] >= 1]
    rows = []
    for _, r in g.iterrows():
        T = pd.Timestamp(r["T"])
        now = T - pd.Timedelta(hours=LEAD)
        resp = predict(r["airport_dep"], T.strftime("%Y-%m-%dT%H:00:00Z"), now.strftime("%Y-%m-%dT%H:00:00Z"))
        if resp["status"] != "ok":
            continue
        tz = config()["airports"][r["airport_dep"]]["tz"]
        rows.append({
            "airport": r["airport_dep"],
            "target_local": T.tz_convert(tz).strftime("%a %d %b %Y %H:00"),
            "now_local": now.tz_convert(tz).strftime("%a %d %b %Y %H:00"),
            "said": resp["risk_level"], "p45": resp["hour_delay_risk"]["p_gt45"],
            "bad_case": resp["delay_estimate"]["bad_case_text"],
            "conf": resp["confidence"]["level"],
            "outcome": (f"{int(r['n_severe'])} of {int(r['n'])} sampled departures severe"
                        + (f", max {int(r['max_delay'])} min" if pd.notna(r["max_delay"]) else "")
                        + (f", {int(r['cancelled'])} cancelled" if r["cancelled"] else "")),
        })
    d = pd.DataFrame(rows)
    hits = (d[d["said"] == "RED"].sort_values("p45", ascending=False)
              .groupby("airport", group_keys=False).head(top))          # top N per airport
    misses = d[d["said"] == "GREEN"].sort_values("p45").head(10)
    n_all = len(d)
    share = d["said"].value_counts().reindex(["RED", "AMBER", "GREEN"]).fillna(0).astype(int).to_dict()

    def table(x):
        out = ["| Airport | Target hour (local) | Set 'Now' to (local) | Tool said | P(>45) | Bad case | Confidence | What happened |",
               "|---|---|---|---|---|---|---|---|"]
        out += [f"| {r.airport} | {r.target_local} | {r.now_local} | {r.said} | {r.p45:.2f} | {r.bad_case} | "
                f"{r.conf} | {r.outcome} |" for r in x.itertuples()]
        return "\n".join(out)

    md = [
        "# Test-period dates with severe delays (generated by `scripts/list_severe_dates.py`)",
        "",
        f"Severe = > 45 min late or cancelled. Test period Apr–Jul 2025, never used for training or tuning. "
        f"Forecast made **{LEAD} h ahead**. The flight data is a ~1% sample, so 'what happened' covers only "
        f"the sampled departures in that hour.",
        "",
        f"**All {n_all} test hours with at least one severe sampled departure, by what the tool said "
        f"6 h earlier:** RED {share['RED']} · AMBER {share['AMBER']} · GREEN {share['GREEN']}.",
        "",
        "**How to use:** in the dashboard pick the airport, set **Now** to the date and hour in the 3rd column, "
        f"choose the target hour (+{LEAD} h), and press Check.",
        "",
        f"## A. Flagged RED and severe delays happened (top {top} per airport by P(>45))",
        table(hits),
        "",
        "## B. Honest misses: severe delays happened but the tool said GREEN (lowest P(>45) first)",
        table(misses),
        "",
    ]
    out = path("reports_dir") / "severe_delay_dates.md"
    out.write_text("\n".join(md))
    print(f"wrote {out} ({n_all} severe hours; RED {share['RED']}, AMBER {share['AMBER']}, GREEN {share['GREEN']})")


if __name__ == "__main__":
    main()
